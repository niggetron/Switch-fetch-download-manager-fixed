// CI overrides: the GitHub Actions workflow passes these to bump the version and
// restrict the build to arm64-v8a. Locally they are absent and the defaults below apply.
val ciVersionCode = (findProperty("ciVersionCode") as String?)?.toIntOrNull() ?: 1
val ciVersionName = (findProperty("ciVersionName") as String?) ?: "1.0"
val ciAbiFilter = findProperty("ciAbiFilter") as String?
// Each CI release gets a distinct applicationId so successive builds install
// side by side instead of trying to "update" an already-signed package.
val ciPackageSuffix = (findProperty("ciPackageSuffix") as String?)?.trim().orEmpty()
val baseApplicationId = "com.aistudio.aetherio.xkqmzp"
val releaseApplicationId =
    if (ciPackageSuffix.isNotBlank() && ciPackageSuffix.matches(Regex("[A-Za-z][A-Za-z0-9_]*"))) {
        "$baseApplicationId.$ciPackageSuffix"
    } else {
        baseApplicationId
    }

android {
  namespace = "com.example"
  compileSdk { version = release(36) { minorApiLevel = 1 } }

  defaultConfig {
    applicationId = releaseApplicationId
    minSdk = 24
    targetSdk = 36
    versionCode = ciVersionCode
    versionName = ciVersionName

    // Restrict the APK to the requested ABI (e.g. arm64-v8a) when running in CI.
    ciAbiFilter?.let { abi -> ndk { abiFilters.add(abi) } }

    testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
  }

  // The CI workflow cross-compiles rust/aether-core into this directory before
  // Gradle runs. Declaring it explicitly keeps the native library in every APK.
  sourceSets {
    getByName("main") {
      jniLibs.srcDirs("src/main/jniLibs")
    }
  }

  // Do not remove or modify these signingConfigs. They are necessary for building, installing,
  // and updating Android apps in AI Studio.
  signingConfigs {
    create("release") {
      val keystorePath = System.getenv("KEYSTORE_PATH") ?: "${rootDir}/my-upload-key.jks"
      storeFile = file(keystorePath)
      storePassword = System.getenv("STORE_PASSWORD")
      keyAlias = "upload"
      keyPassword = System.getenv("KEY_PASSWORD")
    }
    create("debugConfig") {
      storeFile = file("${rootDir}/debug.keystore")
      storePassword = "android"
      keyAlias = "androiddebugkey"
      keyPassword = "android"
    }
  }

  buildTypes {
    release {
      isCrunchPngs = false
      isMinifyEnabled = false
      proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
      // Do not remove or modify this signingConfig assignment. It is necessary for Android apps in
      // AI Studio.
      signingConfig = signingConfigs.getByName("release")
    }
    debug {
      // Do not remove or modify this signingConfig assignment. It is necessary for Android apps in
      // AI Studio.
      signingConfig = signingConfigs.getByName("debugConfig")
    }
  }
  compileOptions {
    sourceCompatibility = JavaVersion.VERSION_11
    targetCompatibility = JavaVersion.VERSION_11
  }
  buildFeatures {
    compose = true
    buildConfig = true
  }
  testOptions { unitTests { isIncludeAndroidResources = true } }
  dependenciesInfo {
    includeInApk = false
    includeInBundle = true
  }
}

